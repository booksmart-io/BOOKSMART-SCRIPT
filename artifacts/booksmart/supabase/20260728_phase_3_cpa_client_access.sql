ALTER TABLE public.messages ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Chat participants view messages" ON public.messages FOR SELECT TO authenticated
USING (
  public.current_app_role() = 'admin'
  OR EXISTS (
    SELECT 1 FROM public.chats
    WHERE chats.id = messages.chat_id
      AND (chats.sender_id = public.current_app_user_id() OR chats.receiver_id = public.current_app_user_id())
  )
);
CREATE POLICY "Chat participants send messages" ON public.messages FOR INSERT TO authenticated
WITH CHECK (
  sender_id = public.current_app_user_id()
  AND EXISTS (
    SELECT 1 FROM public.chats
    WHERE chats.id = messages.chat_id
      AND (chats.sender_id = public.current_app_user_id() OR chats.receiver_id = public.current_app_user_id())
  )
);
CREATE POLICY "Recipients update message state" ON public.messages FOR UPDATE TO authenticated
USING (
  EXISTS (
    SELECT 1 FROM public.chats
    WHERE chats.id = messages.chat_id
      AND (chats.sender_id = public.current_app_user_id() OR chats.receiver_id = public.current_app_user_id())
  )
)
WITH CHECK (
  EXISTS (
    SELECT 1 FROM public.chats
    WHERE chats.id = messages.chat_id
      AND (chats.sender_id = public.current_app_user_id() OR chats.receiver_id = public.current_app_user_id())
  )
);

